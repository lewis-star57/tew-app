const buildChoices = (
  phrase: ChineseSpotPhraseSeed,
  index: number,
  allPhrases: ChineseSpotPhraseSeed[]
): string[] => {
  const sameSpotCandidates = allPhrases
    .filter((candidate) => candidate.spotId === phrase.spotId && candidate.id !== phrase.id)
    .map((candidate) => candidate.text);
  const fallbackCandidates = allPhrases
    .filter((candidate) => candidate.id !== phrase.id)
    .map((candidate) => candidate.text);
  const candidates = sameSpotCandidates.length >= 3 ? sameSpotCandidates : fallbackCandidates;
  const wrongChoices: string[] = [];

  for (let offset = 1; wrongChoices.length < 3 && offset <= candidates.length * 2; offset += 1) {
    const candidate = candidates[(index + offset * 3) % candidates.length];

    if (candidate !== phrase.text && !wrongChoices.includes(candidate)) {
      wrongChoices.push(candidate);
    }
  }

  return [phrase.text, ...wrongChoices];
};

export const CHINESE_SPOT_PHRASES: Phrase[] = chineseSpotPhraseSeeds.map((phrase, index, allPhrases) => ({
  ...phrase,
  language: 'chinese',
  english: phrase.text,
  choices: buildChoices(phrase, index, allPhrases),
}));
