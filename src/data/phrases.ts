const allPhraseSeeds = [...phraseSeeds, ...spotPhraseSeeds];

const getSpotId = (phrase: PhraseSeed): SpotId => {
  if (phrase.spotId) {
    return phrase.spotId;
  }

  const [, rawNumber] = phrase.id.split('-');
  const number = Number(rawNumber);

  if (phrase.category === 'business') {
    return 'office';
  }

  if (phrase.category === 'daily') {
    if (number <= 18 || [23, 27, 32, 33, 35, 36, 37].includes(number)) {
      return 'home';
    }

    return 'park';
  }

  if ([1, 2, 7, 12, 18, 19, 28, 29].includes(number)) {
    return 'station';
  }

  if ([10, 15, 16].includes(number)) {
    return 'cafe';
  }

  if ([3, 4, 9, 14, 30].includes(number)) {
    return 'convenience_store';
  }

  if ([5, 17, 26].includes(number)) {
    return 'restaurant';
  }

  return 'hotel';
};

